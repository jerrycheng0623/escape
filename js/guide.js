import {state,done} from './state.js';
// Derived from existing save fields: old version-1 saves need no migration.
export function guide(){
 const step=(chapter,task,action,next)=>({chapter,task,action,next});
 switch(state.scene){
 case 0:return state.introRead?step('序章・來信之後','前往電梯','櫃檯紀錄已收進筆記。回到房間中央，朝已開啟的前方門口走。','穿過門口，調查不存在的四樓。'):step('序章・來信之後','確認自己的入住紀錄','走近櫃檯，轉頭對準「住宿登記簿」，出現 E 提示後按 E。讀完兩頁文字。','記下入住人數，再從前方門口前往電梯。');
 case 1:if(!done(1))return step('第一關・不存在的四樓','啟用被隱藏的樓層','靠近左側「樓層與維護」，按 E。對照維修路線卡，依工序輸入四個樓層，再確認。','維護完成後，還要排除人像計數異常，電梯才會開門。');
 if(!done(2))return step('第一關・不存在的四樓','排除多出來的乘客計數','靠近右側「鏡面計數」，按 E。比較重量、主攝影與輔助通道，再重新檢查。','乘客回到單人範圍後，走出前方電梯門。');
 return step('第一關・已完成','離開電梯','門已開啟。走回車廂中央，朝前方門口前進。','抵達四樓走廊，找到404號房。');
 case 2:return state.corDoor?step('四樓走廊','走進404號房','房門已開。朝前方門口走入，無須再按按鍵。','先查看房內書桌的房客資料。'):step('四樓走廊','開啟404號房','沿走廊向前，靠近「404」房門，準星對準標示後按 E。','門開後直接往前走，進入客房。');
 case 3:if(!done(3))return step('第二關・住宿登記簿','比對四位失蹤房客','到左側書桌，對準「住宿登記簿」按 E。用鑰匙牌對照表格，依年份交換照片，再核對。','讀完照片背面的警告，門外將有人詢問人數。');
 if(!done(4))return step('第二關・門外的聲音','決定如何回應敲門','回到門外問答，依公告和照片警告作選擇；也可保持沉默。查看筆記時倒數暫停。','問答結束後，浴室通道會解除封鎖。');
 return step('第二關・已完成','調查浴室','浴室已解封。你可先到右側查看床邊變化，再朝前方開啟的通道走。','下一步在浴室鏡前比較五處異常。');
 case 4:if(!done(5))return step('第三關・另一個自己','找出鏡中五處不同','走近前方「鏡面」，按 E。比較兩張快照的狀態和數量，點選鏡面標示。','找齊五處後，繼續操作照片與門禁。');
 if(!done(6))return step('第三關・照片校準','還原照片上的門禁線索','靠近右側「照片與門禁」，按 E。依介面步驟翻轉、遮臉、對齊，再按編號讀四角。','輸入完整門禁碼後，鏡後通道會開啟。');
 return step('第三關・已完成','穿過鏡後通道','照片校準完成，碎片B已收好。從房間中央朝前方開啟的通道前進。','在監控室重建當年的事件順序。');
 case 5:if(!done(7))return step('第四關・重播的監視器','重建監視器事件','到左側「監控回放」按 E。依行李、電話與櫃檯受理狀態，交換四段畫面。','核對歷史影像，再檢查通道時間。');
 if(!done(8))return step('第四關・超前的影像','中止超前通道','到右側「通道控制」按 E。以母鐘為準比對各畫面，選出異常來源，使用實際斷訊。','斷訊成功後，前方通道通往檔案室。');
 return step('第四關・已完成','進入檔案室','碎片C已取得，異常訊號已中止。朝前方門口繼續。','把四份報告碎片拼合，查明登記規則。');
 case 6:if(!done(9))return step('第五關・房客的身分','拼合內部報告','到左側「調查報告」按 E。依頁眉編號排列碎片，讀完文件並完成核對題。','條款核對後管理抽屜解鎖；仍須完成來源分析。');
 if(!done(10))return step('第五關・來源分析','追查第二份紀錄的來源','到右側「來源終端」按 E。排列證據，核對每年都相同的來源。左側抽屜已可取管理員印章。','來源確認後，可走服務走道回櫃檯；印章需另外拿取。');
 return state.inventory.includes('管理員印章')?step('第五關・已完成','帶著證據回到櫃檯','條款、來源與管理員印章已備齊。朝前方門口進入服務走道。','最後到櫃檯比對退房預覽與原始入住頁，再作選擇。'):step('第五關・離開前確認','查看已解鎖的管理抽屜','若要處理無效登記，先到左側「管理抽屜」按 E，按「取走印章」。也可先前往櫃檯。','前方通道可離開；尚未確認退房前，都能原路回來取章。');
 case 7:return step('服務走道','返回櫃檯','沿走道朝前方出口前進；若需補齊物品，轉身沿來路回檔案室。','到櫃檯按 E，讀清楚預覽後再確認。');
 case 8:return step('第六關・退房','作出最後的登記決定','靠近櫃檯「退房」，按 E。核對本人與候補的差別，預覽可取消；原始入住頁提供另一種處理方式。',state.inventory.includes('管理員印章')?'已攜帶印章：可翻到原始入住頁，核對撤銷條件。確認後觀看事件尾聲。':'尚未拿取印章：可轉身沿服務走道回檔案室。確認後觀看事件尾聲。');
 default:return step('調查中','查看筆記','按 J 核對證據，靠近帶標示的物件按 E。','通道開啟後直接步行通過。');
 }
}
export function guideHTML(){const g=guide();return `<aside class="guide-card"><small>${g.chapter}</small><h3>現在：${g.task}</h3><p>${g.action}</p><p class="guide-next">接著：${g.next}</p></aside>`;}
